package com.kairos.backend.training;

import java.time.Instant;
import java.time.LocalDate;
import java.util.List;

import com.kairos.backend.common.ClientIds;

import jakarta.validation.Valid;
import jakarta.validation.constraints.DecimalMax;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;

/**
 * Wire shape of a training session (frontend: TrainingSessionDto in src/data/api/contract.ts).
 * {@code id} is generated by the client and makes a repeated POST idempotent.
 */
public record TrainingSessionDto(
    @NotNull @Pattern(regexp = ClientIds.PATTERN, message = ClientIds.MESSAGE) String id,
    @NotNull LocalDate date,
    @NotBlank @Size(max = 120) String name,
    @NotNull @Pattern(regexp = "strength|hypertrophy|power|endurance|deload|cardio|sport-specific") String type,
    @NotNull @Min(1) @Max(1440) Integer durationMinutes,
    @NotEmpty @Size(max = 40) List<@Valid @NotNull ExerciseDto> exercises) {

    public record ExerciseDto(
        @NotNull @Pattern(regexp = ClientIds.PATTERN, message = ClientIds.MESSAGE) String id,
        @NotBlank @Size(max = 64) String exerciseId,
        @NotEmpty @Size(max = 100) List<@Valid @NotNull SetDto> sets) {
    }

    public record SetDto(
        @NotNull @Pattern(regexp = ClientIds.PATTERN, message = ClientIds.MESSAGE) String id,
        @NotNull @Min(1) @Max(1000) Integer setNumber,
        @NotNull @DecimalMin("0") @DecimalMax("1000") Double weightKg,
        @NotNull @Min(1) @Max(1000) Integer reps,
        @DecimalMin("1") @DecimalMax("10") Double rpe,
        @Min(0) @Max(86400) Integer restSeconds,
        @NotNull Instant performedAt) {
    }

    static TrainingSessionDto of(TrainingSession s) {
        return new TrainingSessionDto(
            s.clientId,
            s.sessionDate,
            s.name,
            s.type,
            s.durationMinutes,
            s.exercises.stream().map(e -> new ExerciseDto(
                e.clientId,
                e.exercise.getId(),
                e.sets.stream().map(set -> new SetDto(
                    set.clientId, (int) set.setNumber, set.weightKg, (int) set.reps, set.rpe, set.restSeconds, set.performedAt)).toList()))
                .toList());
    }
}
